import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

def plot_migration_results(csv_file):
    # 1. Load Data
    # CSV format: timestamp_ns, throughput_bps, buffer_bytes
    data = pd.read_csv(csv_file, names=['ts', 'tput', 'buffer'])

    # Normalize time to seconds starting from 0
    data['ts_sec'] = (data['ts'] - data['ts'].iloc[0]) / 1e9
    data['tput_mbps'] = data['tput'] / 1e6
    data['buffer_kb'] = data['buffer'] / 1024

    fig, ax1 = plt.subplots(figsize=(10, 6))

    # --- Plot Throughput (Left Axis) ---
    color_tput = 'tab:blue'
    ax1.set_xlabel('Time (s)', fontsize=12)
    ax1.set_ylabel('DL Throughput (Mbps)', color=color_tput, fontsize=12)
    ax1.plot(data['ts_sec'], data['tput_mbps'], color=color_tput, linewidth=2, label='Throughput')
    ax1.tick_params(axis='y', labelcolor=color_tput)
    ax1.grid(True, linestyle='--', alpha=0.6)

    # --- Plot RLC Buffer (Right Axis) ---
    ax2 = ax1.twinx()
    color_buf = 'tab:red'
    ax2.set_ylabel('RLC Buffer Occupancy (KB)', color=color_buf, fontsize=12)
    ax2.fill_between(data['ts_sec'], data['buffer_kb'], color=color_buf, alpha=0.3, label='RLC Buffer')
    ax2.tick_params(axis='y', labelcolor=color_buf)

    # --- Annotate the Migration Window ---
    # Find the point where buffer peaks (the migration event)
    peak_idx = data['buffer_kb'].idxmax()
    peak_time = data['ts_sec'].iloc[peak_idx]

    plt.axvspan(peak_time - 0.005, peak_time + 0.005, color='gray', alpha=0.2, label='Migration Window')
    plt.annotate('Zero-RTT Bind', xy=(peak_time, data['buffer_kb'].max()),
                 xytext=(peak_time+0.1, data['buffer_kb'].max()*1.1),
                 arrowprops=dict(facecolor='black', shrink=0.05, width=1, headwidth=5))

    plt.title('Mosaic5G/FlexRIC: User-Plane Impact of Stateful Slice Migration', fontsize=14)
    fig.tight_layout()

    # Save for LaTeX document
    plt.savefig('migration_impact.pdf', format='pdf')
    print("✅ Plot saved as migration_impact.pdf")
    plt.show()

if __name__ == "__main__":
    plot_migration_results('migration_bench.csv')
